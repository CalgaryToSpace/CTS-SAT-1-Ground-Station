"""Overpass prediction for the web UI's Overpasses page: loads the
satellite's latest TLE from step 7's TLE history (`tle_history.parquet`),
propagates it with SGP4 (via `satkit`), and finds every window where it's
above a ground station's horizon.

Pure data layer: no NiceGUI/rendering concerns live here -- see
`overpasses_page` for the page itself.
"""

